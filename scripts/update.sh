#!/bin/bash
# Обновление установки: свежий код -> образ -> подъём -> проверка, что новый конфиг
# прокси ДЕЙСТВИТЕЛЬНО применился.
#
# Последний шаг выглядит лишним ровно до первого раза, когда он срабатывает. `up -d`
# контейнер прокси не пересоздаёт: содержимое смонтированного каталога в хеш настроек
# не входит. Новый конфиг лежит на диске, работает старый, снаружи ничего не сломано —
# просто изменений нет. Проверка стоит секунды, а ловит целый класс таких отказов.
#
# Файл окружения этот скрипт не трогает: секреты установки живут только в нём.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

COMPOSE="docker compose -f docker-compose.prod.yml"
ENV_PATH="$ROOT/.env"

say() { printf '%s\n' "$*"; }
step() { printf '\n== %s ==\n' "$*"; }
die() {
	printf '\n!! %s\n' "$*" >&2
	exit 1
}

# Свой временный каталог, а не фиксированное имя в общем /tmp: туда пишет кто угодно,
# и подложенная заранее символическая ссылка увела бы `curl -o` в чужой файл — правами
# того, кто запускает обновление, а запускают его обычно от root. Та же идиома, что в
# doctor.sh; убирается на любом выходе, включая обрыв.
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

[ -f "$ENV_PATH" ] || die "файла окружения нет — установка ещё не делалась: ./scripts/install.sh ваш-домен.ru"

env_value() {
	# Разбор файла окружения теми же формами записи, что понимает docker compose:
	# `KEY=value`, `export KEY=value`, пробелы вокруг знака равенства, значение в кавычках
	# и хвостовой комментарий у значения без кавычек. Разойдясь с compose, этот разбор
	# ставит неверный диагноз на ИСПРАВНОЙ машине — а чинить его будет некому.
	sed -n -E "s/^[[:space:]]*(export[[:space:]]+)?$1[[:space:]]*=[[:space:]]*//p" "$ENV_PATH" |
		tail -1 |
		sed -E -e 's/^"([^"]*)".*$/\1/;t' -e "s/^'([^']*)'.*\$/\1/;t" -e 's/[[:space:]]+#.*$//' -e 's/[[:space:]]+$//'
}

DOMAIN="$(env_value IG_DOMAIN)"
[ -n "$DOMAIN" ] || die "в файле окружения не задан IG_DOMAIN"

step "1/4 свежий код"
if [ -d "$ROOT/.git" ]; then
	git -C "$ROOT" pull --ff-only ||
		die "$(printf 'git не смог обновить каталог.\n   Обычно причина одна: файлы пакета правились руками. Посмотрите git status,\n   а вернуть их к исходному виду можно так: git checkout -- .\n\n   НЕ запускайте «git clean -xfd»: он удаляет и файл окружения — тот самый, где лежат\n   все секреты установки. Второй копии у них нет, а повторная установка не поможет:\n   пароль роли задаётся один раз, при создании базы, и в томе останется прежний.\n   Перед любой уборкой сделайте копию файла окружения ВНЕ этого каталога.')"
else
	say "каталог не из git — обновлять нечем, пересоберу то, что лежит на диске"
fi

step "2/4 образ"
$COMPOSE build instagram-service

step "3/4 подъём"
# Миграции применяет сам сервис на старте, под блокировкой: отдельный шаг здесь означал бы
# второй способ их накатывать. Провалившаяся миграция не даст контейнеру стать здоровым,
# и `--wait` вернёт ошибку — то есть отдельная проверка не нужна и здесь.
if ! $COMPOSE up -d --wait; then
	$COMPOSE ps || true
	$COMPOSE logs --tail=30 instagram-service || true
	die "состав не поднялся — смотрите журнал выше"
fi
say "прокси, база и сервис отвечают на проверки здоровья"

step "4/4 конфиг прокси: применился или нет"
# Приговор выносит НАБЛЮДАЕМЫЙ ЭФФЕКТ, а не код возврата: `caddy reload` возвращает ноль,
# перечитав ровно то, что видит сам. Признак применённого конфига — 403 с ПУСТЫМ телом
# на машинной админке: приложение на этом же адресе отвечает 403 с телом, а с верным
# ключом и вовсе 200, поэтому по коду ответа эти случаи неразличимы.
caddy_applied() {
	local code
	code="$(curl -sS --max-time 10 -o "$TMP/admin-body" -w '%{http_code}' "https://$DOMAIN/ig/admin/state")" || return 1
	[ "$code" = "403" ] || return 1
	[ ! -s "$TMP/admin-body" ] || return 1
	code="$(curl -sS --max-time 10 -o /dev/null -w '%{http_code}' "https://$DOMAIN/ig/health")" || return 1
	[ "$code" = "200" ] || return 1
	return 0
}

# Не посчиталось (нет sha256sum) — пустая строка не совпадёт ни с чем, и прокси
# пересоздастся. Молчаливый обрыв установки из-за отсутствующей утилиты хуже лишней
# пересборки контейнера, которая стоит пару секунд.
host_sum="$(sha256sum "$ROOT/caddy/Caddyfile" | cut -d' ' -f1 || true)"
cont_sum="$($COMPOSE exec -T caddy sha256sum /etc/caddy/Caddyfile 2>/dev/null | cut -d' ' -f1)" || cont_sum=""
if [ "$host_sum" = "$cont_sum" ]; then
	say "контейнер видит тот же файл, что лежит в каталоге — перечитываю конфиг"
	$COMPOSE exec -T caddy caddy reload --config /etc/caddy/Caddyfile ||
		say "перечитать не удалось; решать будет проверка ниже, а не этот код возврата"
else
	say "контейнер видит другой файл (или не отвечает) — пересоздаю прокси"
	$COMPOSE up -d --force-recreate caddy
fi

for _ in 1 2 3 4 5 6; do
	if caddy_applied; then
		say "конфиг применился: машинная админка закрыта снаружи, публичные адреса живы"
		printf '\nОбновление закончено. Проверить установку целиком: ./scripts/doctor.sh\n'
		exit 0
	fi
	sleep 5
done

$COMPOSE logs --tail=20 caddy || true
die "$(printf 'прокси отвечает не так, как обязан: машинная админка снаружи должна давать 403\n   с ПУСТЫМ телом, а публичные адреса — 200. Значит либо конфиг не применился и работает\n   старый, либо применился не тот. Запустите ./scripts/doctor.sh — он покажет, какая\n   именно строка отвечает неправильно.')"
