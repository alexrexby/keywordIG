# Запасной путь (панель недоступна, или сменили IG_TOKEN_KEY — тогда строка перестаёт
# расшифровываться) РОВНО в таком порядке, иначе рестарт ничего не изменит:
#   1) в базе установки: delete from instagram.ig_token;
