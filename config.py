#
# ПОЧИНКА ПОСЛЕ ПРОТУХАНИЯ — без правки файлов и без рестарта: пройдите Instagram
# Business Login и вставьте свежий токен в панели (PANEL_URL выше, раздел «Токен»).
# Запись снимает пометку «мёртвый», и диспетчер разбирает накопившуюся очередь сам.
