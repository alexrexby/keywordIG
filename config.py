def _positive_int(name: str, default: int) -> int:
    """Кривое значение не роняет старт: приёмник вебхуков важнее темпа отправки."""
    raw = os.environ.get(name, "").strip()
    return int(raw) if raw.isdigit() and int(raw) > 0 else default


