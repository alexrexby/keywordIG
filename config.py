def _limit_int(name: str, default: int) -> int:
    """Целое, где НОЛЬ — осмысленное значение («снять ограничение»), а не «не задано».

    Отдельно от _positive_int намеренно: там ноль сломал бы темп отправки (деление на
    интервал), здесь он его отменяет. Одна функция на оба смысла молча превращала бы
    «0» в значение по умолчанию — то есть говорила бы человеку не то, что делает.
    """
    raw = os.environ.get(name, "").strip()
    return int(raw) if raw.isdigit() else default


# Сколько хранятся КАРТОЧКИ ОБРАЩЕНИЙ (instagram.ig_delivery): кто написал, что написал,
# что ему ответили. Это число уходит в публичную политику конфиденциальности дословно,
# поэтому оно одно на код и на документ: два источника (число в коде и текст на странице)
# разъезжаются на первой же правке, и тогда политика обещает то, чего сервис не делает.
# 0 — не удалять ничего; страница в этом случае честно пишет «пока работает сервис».
#
# Что чистка НЕ трогает и почему: instagram.ig_contact_rule («этому человеку по этому
# правилу материал уже выдавали»). Снять эту отметку — значит выдать материал второй раз
# тому, кто его уже получил; в ней нет ни текста, ни имени, только пара «правило + номер
# человека». Обещание «дважды одно и то же не отправляем» стоит в той же политике.
DELIVERY_RETENTION_DAYS = _limit_int("IG_DELIVERY_RETENTION_DAYS", 365)

