-- Состояние установки, которое обязано пережить рестарт.
--
-- Сюда попадает ТОЛЬКО то, что по природе живёт в памяти процесса, но обязано её пережить.
-- Это не свалка настроек: настройки живут в окружении, данные — в своих таблицах.
-- Проверка при добавлении колонки одна: «врёт ли эта величина сразу после рестарта, и
-- читает ли её человек как факт о мире».
--
-- Что уже не прошло эту проверку:
--   1) состояние канала аварийных сообщений. Панель строит на нём вердикт, а после
--      каждого деплоя и каждой перезагрузки хоста показывала «канал не проверен ни разу»
--      и этим ВЫТЕСНЯЛА настоящие диагнозы — «уведомлений не приходило» и «сервис слушает
--      чужой аккаунт». То есть инструмент диагностики врал ровно в той строке, ради
--      которой его открывают;
--   2) отзыв сессий панели. Кнопка «Выйти» гасила cookie в текущем браузере и метку
--      в памяти процесса — после рестарта старая подписанная cookie снова годилась.
--      Панель открывают в том числе с чужого телефона в момент аварии; кнопка, которая
--      не выходит, хуже отсутствующей.
--
-- Одна строка, как у ig_token: установка одна. CHECK (id = 1) — это не ограничение,
-- а выражение модели.
CREATE TABLE instagram.ig_state (
  id                    int         PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  -- Время последней УСПЕШНОЙ доставки сигнала. «Функция не упала» и «сообщение дошло» —
  -- разные утверждения; наружу отдаётся именно время, а не флаг успеха.
  alert_ok_at           timestamptz,
  -- Описание последнего отказа мессенджера («chat not found», «Unauthorized»).
  -- Токена бота здесь нет и быть не должно: он лежит в ПУТИ запроса, а не в ответе.
  alert_error           text,
  -- Сессии панели, выданные раньше этого момента, недействительны.
  sessions_valid_after  timestamptz,
  updated_at            timestamptz NOT NULL DEFAULT now()
);

