-- CHECK на dm_text мерил не то. Лимит платформы (1000 байт) относится к СООБЩЕНИЮ,
-- то есть к раскрытому тексту, а ограничение стояло на сыром шаблоне — вместе со всеми
-- вариантами рандомайзера. Правило с двумя вариантами по 600 байт укладывается в лимит
-- любым раскрытием (615 байт худшее), а база его не принимала: бизнес-правило в схеме
-- отменяло главную фичу движка текстов.
--
-- Настоящая проверка живёт там, где она честная, — rules.unconfigured() меряет
-- longest(dm_text), то есть худшее сочетание вариантов, и отсекает правило ДО первого
-- обращения к Meta. Здесь остаётся страховка от абсурда: 4096 байт — тот же потолок,
-- что у rules.MAX_TEMPLATE_BYTES (дальше шаблон не разбирается вовсе), поэтому админка
-- до этого CHECK при работающем коде не доходит, и это правильно: схема защищает от
-- записи в обход кода, а не дублирует его логику.
ALTER TABLE instagram.ig_rule DROP CONSTRAINT ig_rule_dm_text_len;
ALTER TABLE instagram.ig_rule
  ADD CONSTRAINT ig_rule_dm_text_len CHECK (octet_length(dm_text) <= 4096);
