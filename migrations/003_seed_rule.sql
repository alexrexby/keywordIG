-- Пример правила: кодовое слово ГАЙД в комментариях → публичный ответ + материал в директ.
-- Это ОБРАЗЕЦ, а не рабочее правило: заполненная форма вместо пустого экрана, чтобы было
-- видно, из чего правило состоит (слово, варианты публичных ответов, ответ на повтор,
-- текст директа, кнопка).
--
-- Правило заведено ВЫКЛЮЧЕННЫМ и с плейсхолдерами намеренно, и предохранителя здесь три:
-- enabled = false; «{{» в тексте директа; ссылка кнопки не подставлена. Пока держится хотя
-- бы один, диспетчер до Meta не идёт вовсе (rules.unconfigured) — иначе первый же
-- комментатор получил бы публичное «отправили в директ» и пустоту в директе.
--
-- Свой текст пишите в панели, а не здесь: миграция для этого не нужна.
-- WHERE NOT EXISTS — чтобы на установке с уже заведёнными правилами сид не сработал.

INSERT INTO instagram.ig_rule (
  name, enabled, "trigger", media_id, keywords, match_mode, priority,
  public_replies, duplicate_replies, dm_text, dm_buttons
)
SELECT
  'ГАЙД — материал в директ',
  false,
  'COMMENT',
  NULL,                       -- любой пост; правило под конкретный пост кладётся рядом с media_id
  ARRAY['гайд'],
  'CONTAINS',
  0,
  -- Вариант выбирается случайно в момент отправки, а {а|б} внутри строки раскрывается
  -- тогда же: под постом не должно стоять пятьдесят одинаковых реплик подряд.
  ARRAY[
    'Отправили в директ 💌',
    'Готово, {смотрите|проверьте} директ',
    'Улетело в директ',
    'Уже у вас в директе',
    'Лови{те|} в директе',
    'Отправили — загляните в директ'
  ],
  -- Ответ тому, кто написал слово повторно: материал второй раз не уходит (запрет
  -- платформы), но молчание под постом видят посторонние — это хуже отказа.
  ARRAY[
    'Уже отправляли — посмотрите директ',
    'Оно у вас в директе, проверьте',
    'Отправляли раньше — загляните в переписку'
  ],
  'Здравствуйте! Это автоответ: сервис увидел кодовое слово в комментариях и сразу отправил обещанное.' || E'\n\n' || 'Внутри: {{ОДНОЙ СТРОКОЙ — ЧТО ЭТО}}' || E'\n\n' || 'Ссылка ниже никуда не денется, но открыть её лучше сразу.',
  '[{"title": "Забрать материал", "url": "https://ЗАМЕНИ-НА-ССЫЛКУ-НА-МАТЕРИАЛ"}]'::jsonb
WHERE NOT EXISTS (SELECT 1 FROM instagram.ig_rule);
