-- Состояние канала аварийных сообщений: пережить рестарт обязано.
--
-- Зачем таблица ради двух полей. «Когда последний сигнал дошёл» и «чем ответил мессенджер»
-- жили в памяти процесса, а панель строит на них вердикт. После каждого рестарта — деплой,
-- перезагрузка хоста, собственный SIGTERM сторожка — панель показывала «канал не проверен
-- ни разу» и этим ВЫТЕСНЯЛА настоящие диагнозы: и «уведомлений не приходило», и «сервис
-- слушает чужой аккаунт». То есть инструмент диагностики после любого рестарта врал именно
-- в той строке, ради которой его открывают. Тот же довод, по которому «приходили ли
-- уведомления когда-либо» спрашивают у последовательности, а не у счётчика строк.
--
-- Одна строка, как у ig_token: канал у установки один. CHECK (id = 1) — это не ограничение,
-- а выражение модели.
CREATE TABLE instagram.ig_alert_channel (
  id          int         PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  -- Время последней УСПЕШНОЙ доставки. «Функция не упала» и «сообщение дошло» — разные
  -- утверждения; наружу отдаётся именно это время, а не флаг успеха.
  last_ok_at  timestamptz,
  -- Описание последнего отказа от мессенджера («chat not found», «Unauthorized»).
  -- Токена бота здесь нет и быть не должно: он лежит в ПУТИ запроса, а не в ответе.
  last_error  text,
  updated_at  timestamptz NOT NULL DEFAULT now()
);

